import { ITEM_TABS } from './items';
import { formatMasteryRank } from './mastery';
import type { ItemState, ManualExtras, MasteryStats, Overrides } from './types';

export function buildMarkdown(
  displayName: string,
  stats: MasteryStats,
  states: ItemState[],
  extras: ManualExtras,
  generatedAt = Date.now(),
): string {
  const generated = new Date(generatedAt).toISOString();
  const title = `Warframe Mastery — ${displayName}`.replace(/"/g, '\\"');
  const completion = (stats.completion * 100).toFixed(1);
  const lines: string[] = [
    '---',
    `title: "${title}"`,
    `generated: ${generated}`,
    `mastery_rank: ${stats.rank}`,
    `mastery_points: ${stats.totalPoints}`,
    `items_mastered: ${stats.masteredCount}`,
    `items_total: ${stats.totalItems}`,
    `completion_percent: ${completion}`,
    '---',
    '',
    `# ${displayName} — Warframe Mastery`,
    '',
    '## Summary',
    '',
    `- Mastery rank: **${formatMasteryRank(stats.rank)}**`,
    `- Mastery points: **${stats.totalPoints.toLocaleString('en-US')}**`,
    `- Items mastered: **${stats.masteredCount.toLocaleString('en-US')} / ${stats.totalItems.toLocaleString('en-US')}**`,
    `- Completion: **${completion}%**`,
    `- Points to next rank: **${stats.pointsToNext.toLocaleString('en-US')}**`,
    '',
    '## Manual progress',
    '',
    `- Junctions: ${extras.junctions}`,
    `- Intrinsic ranks: ${extras.intrinsics}`,
    `- Star Chart points: ${extras.starChartPoints.toLocaleString('en-US')}`,
    '',
  ];

  for (const tab of ITEM_TABS) {
    const tabStates = states
      .filter((state) => state.item.tab === tab.id)
      .sort((a, b) => a.item.name.localeCompare(b.item.name));
    if (tabStates.length === 0) continue;
    lines.push(`## ${tab.label}`, '');
    for (const state of tabStates) {
      const checkbox = state.mastered ? '[x]' : '[ ]';
      const requirement = state.mastered ? '' : ` (MR ${state.item.masteryReq})`;
      lines.push(`- ${checkbox} ${state.item.name}${requirement}`);
    }
    lines.push('');
  }

  lines.push('---', '');
  lines.push('Generated by Tenno Ledger. Unofficial fan project, not affiliated with Digital Extremes.');
  return lines.join('\n');
}

export function buildJsonExport(
  profile: { displayName: string; playerLevel: number; source: string },
  stats: MasteryStats,
  states: ItemState[],
  extras: ManualExtras,
  overrides: Overrides,
  generatedAt = Date.now(),
): string {
  return JSON.stringify(
    {
      format: 'tenno-ledger-export',
      version: 1,
      generatedAt: new Date(generatedAt).toISOString(),
      profile: {
        displayName: profile.displayName,
        profileMasteryRank: profile.playerLevel,
        source: profile.source,
      },
      mastery: stats,
      manual: extras,
      overrides,
      items: states
        .slice()
        .sort((a, b) => a.item.name.localeCompare(b.item.name))
        .map((state) => ({
          uniqueName: state.item.uniqueName,
          name: state.item.name,
          tab: state.item.tab,
          category: state.item.category,
          type: state.item.type,
          masteryReq: state.item.masteryReq,
          maxRank: state.item.maxRank,
          rank: state.rank,
          mastered: state.mastered,
          points: state.points,
          pointsAvailable: state.item.points,
          xp: state.xp,
          remainingXp: state.remainingXp,
          override: state.override ?? null,
        })),
    },
    null,
    2,
  );
}

export function downloadText(filename: string, text: string, mime: string): void {
  const blob = new Blob([text], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  anchor.rel = 'noopener';
  document.body.append(anchor);
  anchor.click();
  anchor.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1_000);
}

export function safeFilename(name: string): string {
  const cleaned = name
    .trim()
    .replace(/[^\w.-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
  return cleaned || 'tenno';
}
